$Script:LogFile = $null

function Start-Log ([string]$Prefix) {
    $Script:LogFile = Join-Path $PSScriptRoot ("{0}_{1}.log" -f $Prefix, (Get-Date -Format 'yyyyMMdd_HHmmss'))
}

function Write-Log {
    param([string]$Message, [string]$Color = 'White')
    Write-Host $Message -ForegroundColor $Color
    if ($Script:LogFile) {
        $Message | Out-File $Script:LogFile -Append -Encoding utf8
    }
}

function Write-SectionHeader ([string]$Title) {
    Write-Log ''
    Write-Log ('  ' + ('=' * 66)) 'Cyan'
    Write-Log ("  $Title") 'Cyan'
    Write-Log ('  ' + ('=' * 66)) 'Cyan'
}

function Write-Tip ([string]$Message) {
    Write-Log ("  [TIP] {0}" -f $Message) 'DarkCyan'
}

function Get-FolderSizeBytes ([string]$Path) {
    $bytes = (Get-ChildItem -LiteralPath $Path -Recurse -ErrorAction SilentlyContinue |
              Where-Object { -not $_.PSIsContainer } |
              Measure-Object -Property Length -Sum).Sum
    if ($bytes) { return [long]$bytes } else { return [long]0 }
}

function Format-Bytes ([long]$Bytes) {
    if ($Bytes -ge 1GB) { return ('{0:N2} GB' -f ($Bytes / 1GB)) }
    if ($Bytes -ge 1MB) { return ('{0:N1} MB' -f ($Bytes / 1MB)) }
    return ('{0} B' -f $Bytes)
}

function Get-FolderSize ([string]$Path) {
    $b = Get-FolderSizeBytes $Path
    return @{ Bytes = $b; Display = Format-Bytes $b }
}

function Normalize ([string]$s) {
    return ($s.ToLower() -replace '[^a-z0-9]', '')
}

function Normalize-Path ([string]$p) {
    return $p.ToLower().TrimEnd('\').TrimEnd('/') -replace '/', '\'
}

function Invoke-ArrApi {
    param([string]$BaseUrl, [string]$ApiKey, [string]$Endpoint, [string]$ApiVersion = 'v3')
    $uri = "$($BaseUrl.TrimEnd('/'))/api/$ApiVersion/$Endpoint"
    try {
        return Invoke-RestMethod -Uri $uri `
            -Headers @{ 'X-Api-Key' = $ApiKey } `
            -Method Get -ErrorAction Stop
    }
    catch {
        Write-Log ("  [ERROR] API call failed: {0}" -f $uri) 'Red'
        Write-Log ("          {0}" -f $_) 'Red'
        return $null
    }
}

function Confirm-LiveAction ([string]$Warning) {
    Write-Log ''
    Write-Log ("  WARNING: {0}" -f $Warning) 'Red'
    Write-Log '  This action cannot be undone. A log will be saved next to this script.' 'Yellow'
    Write-Log ''
    $confirm = Read-Host '  Type YES to proceed, or anything else to abort'
    if ($confirm -ne 'YES') {
        Write-Log '  Aborted. No changes were made.' 'Yellow'
        return $false
    }
    Write-Log ''
    return $true
}

# ================================================================
#  TOOL 1: FOLDERBOY CLEANER
# ================================================================
function Invoke-FolderBoyCleaner {
    param([bool]$LiveDelete = $false)

    Start-Log 'FolderBoy'
    $modeLabel = if ($LiveDelete) { 'Live Delete' } else { 'Dry Run' }

    Write-Log ''
    Write-Log '  ============================================================' 'Cyan'
    Write-Log ("   FolderBoy Cleaner -- {0}" -f $modeLabel) 'Cyan'
    Write-Log ('   {0}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')) 'Cyan'
    Write-Log '  ============================================================' 'Cyan'

    if (-not $LiveDelete) {
        Write-Log ''
        Write-Log '  DRY RUN MODE: No files or folders will be deleted.' 'Cyan'
        Write-Log '  This run shows you exactly what WOULD be removed.' 'Cyan'
        Write-Log '  Review the output, then re-run and choose Live Delete to apply.' 'Cyan'
    }

    Write-Log ''
    Write-Log '  Select media type:' 'Cyan'
    Write-Log ''
    foreach ($key in $FolderBoyPresets.Keys) {
        Write-Log ("    ({0}) {1}" -f $key, $FolderBoyPresets[$key].Label)
    }
    Write-Log ''
    do { $choice = Read-Host '  Choice' } until ($FolderBoyPresets.Contains($choice))
    $preset = $FolderBoyPresets[$choice]

    if ($choice -eq ($FolderBoyPresets.Keys | Select-Object -Last 1)) {
        # Custom preset
        $customInput = Read-Host '  Enter extensions comma-separated (e.g. mp3,flac,wav)'
        $mediaExts = $customInput -split ',' | ForEach-Object {
            $e = $_.Trim().ToLower()
            if ($e -notmatch '^\.' ) { ".$e" } else { $e }
        }
        $label     = 'Custom'
        $scanPaths = @(Read-Host '  Enter root path to scan')
    } else {
        $mediaExts = $preset.Exts
        $label     = $preset.Label
        $scanPaths = $preset.Paths

        if ($preset.Paths.Count -gt 1) {
            Write-Log ''
            Write-Log '  Select path to scan:' 'Cyan'
            Write-Log ''
            for ($i = 0; $i -lt $preset.Paths.Count; $i++) {
                Write-Log ("    ({0}) {1}" -f ($i + 1), $preset.Paths[$i])
            }
            Write-Log ("    ({0}) All paths" -f ($preset.Paths.Count + 1))
            Write-Log ''
            do {
                $pathChoice = Read-Host '  Choice'
                $pathIdx = 0
                $validPath = [int]::TryParse($pathChoice, [ref]$pathIdx) -and
                             $pathIdx -ge 1 -and $pathIdx -le ($preset.Paths.Count + 1)
            } until ($validPath)
            if ($pathIdx -le $preset.Paths.Count) {
                $scanPaths = @($preset.Paths[$pathIdx - 1])
            }
        }
    }

    Write-Log ''
    Write-Log ("  Scanning for  : {0}" -f $label) 'Yellow'
    Write-Log ("  Extensions    : {0}" -f ($mediaExts -join ', ')) 'Yellow'
    foreach ($p in $scanPaths) { Write-Log ("  Path          : {0}" -f $p) 'Yellow' }

    if ($LiveDelete) {
        if (-not (Confirm-LiveAction 'This will permanently delete folders containing no media files.')) { return }
    } else {
        Write-Log ''
    }

    $toDelete   = [System.Collections.Generic.List[string]]::new()
    $totalBytes = [long]0
    $extTally   = @{}
    $deleted    = [System.Collections.Generic.List[string]]::new()
    $failed     = [System.Collections.Generic.List[string]]::new()

    Write-Log ('  ' + ('-' * 66))

    foreach ($root in $scanPaths) {
        if (-not (Test-Path -LiteralPath $root)) {
            Write-Log ("  [WARN] Path not found: {0}" -f $root) 'Yellow'
            continue
        }

        $allFolders = Get-ChildItem -Path $root -Recurse -ErrorAction SilentlyContinue |
                      Where-Object { $_.PSIsContainer } |
                      Sort-Object { $_.FullName.Length } -Descending

        Write-Log ("  Scanning {0}  ({1} subfolders)" -f $root, $allFolders.Count) 'White'

        foreach ($folder in $allFolders) {
            if ($LiveDelete -and -not (Test-Path -LiteralPath $folder.FullName)) { continue }

            $hasMedia = Get-ChildItem -LiteralPath $folder.FullName -Recurse -ErrorAction SilentlyContinue |
                        Where-Object { -not $_.PSIsContainer -and $mediaExts -contains $_.Extension.ToLower() } |
                        Select-Object -First 1

            if (-not $hasMedia) {
                $files     = Get-ChildItem -LiteralPath $folder.FullName -Recurse -ErrorAction SilentlyContinue |
                             Where-Object { -not $_.PSIsContainer }
                $sizeBytes = if (($s = ($files | Measure-Object -Property Length -Sum).Sum)) { [long]$s } else { [long]0 }
                $sizeMB    = [math]::Round($sizeBytes / 1MB, 1)

                foreach ($file in $files) {
                    $ext = if ($file.Extension) { $file.Extension.ToLower() } else { '(no ext)' }
                    if (-not $extTally[$ext]) { $extTally[$ext] = @{ Count = 0; Bytes = [long]0 } }
                    $extTally[$ext].Count++
                    $extTally[$ext].Bytes += $file.Length
                }

                if ($LiveDelete) {
                    try {
                        Remove-Item -LiteralPath $folder.FullName -Recurse -Force -ErrorAction Stop
                        Write-Log ("  [DELETED] {0}  ({1} MB)" -f $folder.FullName.PadRight($PathPad), $sizeMB) 'Green'
                        $deleted.Add($folder.FullName)
                        $totalBytes += $sizeBytes
                    } catch {
                        Write-Log ("  [FAILED]  {0}" -f $folder.FullName) 'Red'
                        Write-Log ("            {0}" -f $_) 'Red'
                        $failed.Add($folder.FullName)
                    }
                } else {
                    Write-Log ("  [WOULD DELETE] {0}  ({1} MB)" -f $folder.FullName.PadRight($PathPad), $sizeMB) 'Yellow'
                    $toDelete.Add($folder.FullName)
                    $totalBytes += $sizeBytes
                }
            }
        }
    }

    $totalGB = [math]::Round($totalBytes / 1GB, 2)
    $totalMB = [math]::Round($totalBytes / 1MB, 1)

    Write-Log ('  ' + ('-' * 66))
    Write-Log ''

    if ($LiveDelete) {
        Write-Log ("  Deleted   : {0}  folders" -f $deleted.Count) 'Green'
        Write-Log ("  Failed    : {0}  folders" -f $failed.Count) $(if ($failed.Count) { 'Red' } else { 'Green' })
        Write-Log ("  Reclaimed : {0} GB  ({1} MB)" -f $totalGB, $totalMB) 'Green'
    } else {
        Write-Log ("  Would delete  : {0}  folders" -f $toDelete.Count) 'Yellow'
        Write-Log ("  Reclaimable   : {0} GB  ({1} MB)" -f $totalGB, $totalMB) 'Yellow'
        Write-Log ''
        Write-Log '  Re-run and choose Live Delete to apply these changes.' 'Cyan'
    }

    if ($extTally.Count) {
        Write-Log ''
        Write-Log '  Non-media file types found in flagged folders:' 'DarkGray'
        Write-Log ('  {0,-22} {1,8}   {2,10}' -f 'Extension', 'Files', 'Size') 'DarkGray'
        $extTally.GetEnumerator() | Sort-Object { $_.Value.Bytes } -Descending | ForEach-Object {
            $extMB = [math]::Round($_.Value.Bytes / 1MB, 1)
            Write-Log ('  {0,-22} {1,8}   {2,7} MB' -f $_.Key, $_.Value.Count, $extMB) 'DarkGray'
        }
    }

    Write-Log ''
    Write-Log ("  Log saved to: {0}" -f $Script:LogFile) 'Cyan'

    return @{ Label = $label; Paths = $scanPaths }
}

