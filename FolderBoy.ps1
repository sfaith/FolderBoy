$Script:LogFile = $null

function Start-Log ([string]$Prefix) {
    $logDir = Join-Path $PSScriptRoot 'Logs'
    if (-not (Test-Path -LiteralPath $logDir)) {
        New-Item -ItemType Directory -Path $logDir -Force | Out-Null
    }
    $Script:LogFile = Join-Path $logDir ("{0}_{1}.log" -f $Prefix, (Get-Date -Format 'yyyyMMdd_HHmmss'))
}

function Write-Log {
    param([string]$Message, [string]$Color = 'White')
    Write-Host $Message -ForegroundColor $Color
    if ($Script:LogFile) {
        $Message | Out-File $Script:LogFile -Append -Encoding utf8
    }
}

function Write-SectionHeader ([string]$Title) {
    Write-Log ''
    Write-Log ('  ' + ('=' * 66)) 'Cyan'
    Write-Log ("  $Title") 'Cyan'
    Write-Log ('  ' + ('=' * 66)) 'Cyan'
}

function Write-Tip ([string]$Message) {
