function Invoke-SonarrGet ([string]$Endpoint) {
    $uri = "$($SonarrConfig.BaseUrl.TrimEnd('/'))/api/v3/$Endpoint"
    try {
        return Invoke-RestMethod -Uri $uri `
            -Headers @{ 'X-Api-Key' = $SonarrConfig.ApiKey } `
            -Method Get -ErrorAction Stop
    }
    catch {
        Write-Log ("  [ERROR] GET {0} -- {1}" -f $uri, $_) 'Red'
        return $null
    }
}

function Invoke-SonarrPut ([string]$Endpoint, [object]$Body) {
    $uri = "$($SonarrConfig.BaseUrl.TrimEnd('/'))/api/v3/$Endpoint"
    try {
        $json  = $Body | ConvertTo-Json -Depth 20 -Compress
        # Send as UTF-8 bytes -- required for series with non-ASCII
        # characters in alternate titles. Sending as a plain string
        # causes Sonarr to return 400 Bad Request for these series.
        $bytes = [System.Text.Encoding]::UTF8.GetBytes($json)
        return Invoke-RestMethod -Uri $uri `
            -Headers @{ 'X-Api-Key' = $SonarrConfig.ApiKey; 'Content-Type' = 'application/json; charset=utf-8' } `
            -Method Put -Body $bytes -ErrorAction Stop
    }
    catch {
        Write-Log ("  [ERROR] PUT {0} -- {1}" -f $uri, $_) 'Red'
        return $null
    }
}

function Get-CleanTitle ([string]$Title) {
    # Mirrors Sonarr's title sanitization:
    # colons become space-dash, forward slash removed,
    # other illegal Windows filename characters removed.
    $clean = $Title -replace ':', ' -'
    $clean = $clean -replace '[\\/<>"\|\?\*]', ''
    $clean = $clean -replace '\s+', ' '
    return $clean.Trim()
}

function Test-TitleMatch ([string]$FolderName, [string]$SonarrTitle) {
    # Returns $true if the folder name (minus tag blocks) normalizes
    # to the same string as the Sonarr title, or matches the title
    # without its disambiguation year.
    # Prevents accidental renames of folders that were manually named
    # differently from what Sonarr would generate.
    $folderBase       = ($FolderName -replace '\{[^}]+\}', '' -replace '\s+', ' ').Trim()
    $normalize        = { param($s) ($s.ToLower() -replace '[^a-z0-9]', '') }
    $normFolder       = & $normalize $folderBase
    $normSonarr       = & $normalize (Get-CleanTitle $SonarrTitle)
    $sonarrNoYear     = (Get-CleanTitle $SonarrTitle) -replace '\s*\(\d{4}\)\s*$', ''
    $normSonarrNoYear = & $normalize $sonarrNoYear
    return ($normFolder -eq $normSonarr) -or ($normFolder -eq $normSonarrNoYear)
}

function Get-TargetFolderName ([string]$Title, [int]$Year, [string]$ImdbId) {
    # Builds: {Series TitleYear} {imdb-{ImdbId}}
    # e.g.   The Wire (2002) {imdb-tt0306414}
    # Does not append year if the clean title already ends with (YYYY).
    $clean = Get-CleanTitle $Title
    if ($Year -gt 0 -and $clean -notmatch '\(\d{4}\)\s*$') {
        return "{0} ({1}) {{imdb-{2}}}" -f $clean, $Year, $ImdbId
    } else {
        return "{0} {{imdb-{1}}}" -f $clean, $ImdbId
    }
}

function Invoke-SonarrRenamer {
    param([bool]$LiveRename = $false)

    Start-Log 'FolderBoy_SonarrRenamer'
    $modeLabel = if ($LiveRename) { 'Live Rename' } else { 'Dry Run' }

    Write-Log ''
    Write-Log '  ============================================================' 'Cyan'
    Write-Log ("   Sonarr Folder Renamer -- {0}" -f $modeLabel) 'Cyan'
    Write-Log ('   {0}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')) 'Cyan'
    Write-Log '  ============================================================' 'Cyan'

    if (-not $LiveRename) {
        Write-Log ''
        Write-Log '  DRY RUN MODE: No folders will be renamed. Sonarr will not be updated.' 'Cyan'
        Write-Log '  This run previews what WOULD be renamed.' 'Cyan'
        Write-Log '  Review the output, then re-run and choose Live Rename to apply.' 'Cyan'
    }

    Write-Log ''
    Write-Tip 'Sonarr Series Folder Format should be: {Series TitleYear} {imdb-{ImdbId}}'
    Write-Tip 'Set in Sonarr: Settings > Media Management > (show advanced) > Series Folder Format'
    Write-Tip 'Guide: https://trash-guides.info/Sonarr/Sonarr-recommended-naming-scheme/'
    Write-Log ''

    if ($LiveRename) {
        if (-not (Confirm-LiveAction 'This will rename series folders on disk and update Sonarr paths via API.')) { return }
    }

    Write-Log '  Fetching Sonarr library...' 'White'
    $allSeries = Invoke-SonarrGet 'series'
    if (-not $allSeries) {
        Write-Log '  Could not reach Sonarr API. Check BaseUrl and ApiKey in FolderBoy.config.ps1.' 'Red'
        return
    }
    Write-Log ("  Found {0} series in Sonarr." -f $allSeries.Count) 'White'
    Write-Log ''

    $counts = @{
        AlreadyTagged = 0; NoImdbId = 0; NoPath = 0
        PathMissing   = 0; Renamed  = 0; Failed = 0; Skipped = 0
    }
    $noImdbList = [System.Collections.Generic.List[string]]::new()
    $failedList = [System.Collections.Generic.List[string]]::new()

    Write-SectionHeader 'PROCESSING SERIES'
    Write-Log ''

    foreach ($series in $allSeries | Sort-Object title) {
        $currentPath = $series.path.TrimEnd('\').TrimEnd('/')
        $title       = $series.title
        $year        = $series.year
        $imdbId      = $series.imdbId
        $seriesId    = $series.id

        if (-not $currentPath) { $counts.NoPath++; continue }

        $folderName = Split-Path $currentPath -Leaf
        $parentDir  = Split-Path $currentPath -Parent

        if ($folderName -match '\{imdb-tt\d+\}') { $counts.AlreadyTagged++; continue }

        if (-not $imdbId) {
            Write-Log ("  [NO IMDB ID] {0}" -f $title) 'Yellow'
            $noImdbList.Add($title)
            $counts.NoImdbId++
            continue
        }

        if (-not (Test-Path -LiteralPath $currentPath)) {
            Write-Log ("  [MISSING]    {0} -- path not found: {1}" -f $title, $currentPath) 'Yellow'
            $counts.PathMissing++
            continue
        }

        if (-not (Test-TitleMatch $folderName $title)) {
            Write-Log ("  [MISMATCH]   {0}" -f $title) 'Yellow'
            Write-Log ("      Folder : {0}" -f $folderName) 'Yellow'
            Write-Log ("      Sonarr : {0}" -f (Get-CleanTitle $title)) 'Yellow'
            Write-Log ("      Skipped -- rename folder manually to match Sonarr title, then re-run.") 'Yellow'
            $counts.Skipped++
            continue
        }

        $newFolderName = Get-TargetFolderName $title $year $imdbId
        $newPath       = Join-Path $parentDir $newFolderName

        if ($folderName -eq $newFolderName) { $counts.AlreadyTagged++; continue }

        if (-not $LiveRename) {
            Write-Log ("  [WOULD RENAME]") 'White'
            Write-Log ("      From : {0}" -f $currentPath) 'White'
            Write-Log ("      To   : {0}" -f $newPath) 'Cyan'
            $counts.Renamed++
        } else {
            if ((Test-Path -LiteralPath $newPath) -and ($newPath -ne $currentPath)) {
                Write-Log ("  [CONFLICT]   {0} -- target folder already exists." -f $title) 'Red'
                $failedList.Add(("{0} -- target folder already exists" -f $title))
                $counts.Failed++
                continue
            }
            try {
                Rename-Item -LiteralPath $currentPath -NewName $newFolderName -ErrorAction Stop
                $series.path = $newPath
                $result = Invoke-SonarrPut "series/$seriesId" $series
                if ($result) {
                    Write-Log ("  [RENAMED]") 'Green'
                    Write-Log ("      From : {0}" -f $currentPath) 'Green'
                    Write-Log ("      To   : {0}" -f $newPath) 'Green'
                    $counts.Renamed++
                } else {
                    Write-Log ("  [API FAIL]   {0} -- folder renamed but Sonarr update failed. Rolling back." -f $title) 'Red'
                    try {
                        Rename-Item -LiteralPath $newPath -NewName $folderName -ErrorAction Stop
                        Write-Log ("               Rollback successful.") 'Yellow'
                    } catch {
                        Write-Log ("               Rollback FAILED. Folder is now at: {0}" -f $newPath) 'Red'
                        Write-Log ("               Manually update the path in Sonarr for this series.") 'Red'
                    }
                    $failedList.Add(("{0} -- Sonarr API update failed" -f $title))
                    $counts.Failed++
                }
            } catch {
                Write-Log ("  [ERROR]      {0} -- {1}" -f $title, $_) 'Red'
                $failedList.Add(("{0} -- {1}" -f $title, $_))
                $counts.Failed++
            }
        }
    }

    Write-Log ''
    Write-SectionHeader 'SUMMARY'
    Write-Log ''

    if ($LiveRename) {
        Write-Log ("  Renamed        : {0}  series" -f $counts.Renamed) 'Green'
        Write-Log ("  Failed         : {0}  series" -f $counts.Failed) $(if ($counts.Failed) { 'Red' } else { 'Green' })
    } else {
        Write-Log ("  Would rename   : {0}  series" -f $counts.Renamed) 'Cyan'
    }
    Write-Log ("  Already tagged : {0}  series" -f $counts.AlreadyTagged) 'White'
    Write-Log ("  No IMDb ID     : {0}  series (cannot tag -- add ID in Sonarr)" -f $counts.NoImdbId) 'Yellow'
    Write-Log ("  Title mismatch : {0}  series (skipped -- rename folder manually)" -f $counts.Skipped) 'Yellow'
    Write-Log ("  Path missing   : {0}  series (Sonarr path not found on disk)" -f $counts.PathMissing) 'Yellow'

    if ($noImdbList.Count) {
        Write-Log ''
        Write-Log '  Series with no IMDb ID in Sonarr:' 'Yellow'
        foreach ($s in $noImdbList | Sort-Object) { Write-Log ("    - {0}" -f $s) 'Yellow' }
        Write-Tip 'To add an IMDb ID: open the series in Sonarr > Edit > External IDs'
    }
    if ($failedList.Count) {
        Write-Log ''
        Write-Log '  Failed renames (require manual attention):' 'Red'
        foreach ($f in $failedList) { Write-Log ("    - {0}" -f $f) 'Red' }
    }

    Write-Log ''
    if (-not $LiveRename) {
        Write-Log '  Re-run and choose Live Rename to apply these changes.' 'Cyan'
    } else {
        Write-Log '  Done.' 'Green'
    }
    Write-Log ("  Log saved to: {0}" -f $Script:LogFile) 'Cyan'
}


# ================================================================
#  TOOL 3: RADARR FOLDER RENAMER
