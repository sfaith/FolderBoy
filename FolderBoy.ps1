function Write-OrphanAppSummary ($AppName, $Stats) {
    Write-Log ''
    Write-Log ("  -- {0} Summary --" -f $AppName) 'Yellow'
    Write-Log ("    Not in {0,-8}: {1,4}  folders" -f $AppName, $Stats.NotInArr.Count) $(if ($Stats.NotInArr.Count) { 'Red' } else { 'Green' })
    Write-Log ("    Needs Review   : {0,4}  folders" -f $Stats.NeedsReview.Count) $(if ($Stats.NeedsReview.Count) { 'Yellow' } else { 'Green' })
    Write-Log ("    Matched OK     : {0,4}  folders" -f $Stats.Matched) 'Green'
}

function Invoke-RadarrScan {
    if (-not $RadarrConfig.Enabled) {
        Write-Log '  Radarr is disabled in config -- skipping.' 'DarkGray'
        return $null
    }

    Write-Log ("  Radarr: {0}" -f $RadarrConfig.BaseUrl) 'White'
    Write-Tip 'Radarr Movie Folder Format (minimum): {Movie CleanTitle} ({Release Year})'
    Write-Tip 'Guide: https://trash-guides.info/Radarr/Radarr-recommended-naming-scheme/'

    $movies = Invoke-ArrApi $RadarrConfig.BaseUrl $RadarrConfig.ApiKey 'movie'
    if (-not $movies) {
        Write-Log '  Could not reach Radarr API. Check BaseUrl and ApiKey in FolderBoy.config.ps1.' 'Red'
        return $null
    }

    $radarrPaths = @{}
    foreach ($m in $movies) {
        if ($m.path) { $radarrPaths[(Normalize-Path $m.path)] = $m.title }
    }
    Write-Log ("  Library: {0} movies  |  {1} with paths set" -f $movies.Count, $radarrPaths.Count) 'White'

    $stats = @{
        NotInArr    = [System.Collections.Generic.List[hashtable]]::new()
        NeedsReview = [System.Collections.Generic.List[hashtable]]::new()
        NameMatched = [System.Collections.Generic.List[hashtable]]::new()
        Matched     = 0
    }

    foreach ($rootPath in $RadarrConfig.Paths) {
        if (-not (Test-Path -LiteralPath $rootPath)) {
            Write-Log ("  [WARN] Path not found: {0}" -f $rootPath) 'Yellow'
            continue
        }
        $folders = Get-ChildItem -LiteralPath $rootPath -Directory -ErrorAction SilentlyContinue
        Write-Log ("  Scanning {0} ({1} folders)" -f $rootPath, $folders.Count) 'White'
        foreach ($folder in $folders) {
            if ($radarrPaths.ContainsKey((Normalize-Path $folder.FullName))) {
                $stats.Matched++
            } else {
                $sz = Get-FolderSize $folder.FullName
                $stats.NotInArr.Add(@{ Path = $folder.FullName; Size = $sz.Display; Bytes = $sz.Bytes; App = 'Radarr' })
            }
        }
    }

    if ($stats.NotInArr.Count) {
        Write-Log ''
        Write-Log '  [ NOT IN RADARR -- folder path not managed by Radarr ]' 'Red'
        Write-Log '  These folders exist on disk but Radarr has no record of them.' 'DarkGray'
        foreach ($item in $stats.NotInArr | Sort-Object { $_.Path }) {
            Write-Log ("    {0}  |  {1}" -f $item.Path.PadRight($PathPad), $item.Size.PadLeft(10)) 'Red'
        }
    }

    Write-OrphanAppSummary 'Radarr' $stats
    return $stats
}

function Invoke-SonarrScan {
    if (-not $SonarrConfig.Enabled) {
        Write-Log '  Sonarr is disabled in config -- skipping.' 'DarkGray'
        return $null
    }

    Write-Log ("  Sonarr: {0}" -f $SonarrConfig.BaseUrl) 'White'
    Write-Tip 'Sonarr Series Folder Format should be: {Series TitleYear} {imdb-{ImdbId}}'
    Write-Tip 'Run the Sonarr Folder Renamer (option 2) to add ID tags to existing folders.'

    $series = Invoke-ArrApi $SonarrConfig.BaseUrl $SonarrConfig.ApiKey 'series'
    if (-not $series) {
        Write-Log '  Could not reach Sonarr API. Check BaseUrl and ApiKey in FolderBoy.config.ps1.' 'Red'
        return $null
    }

    $imdbLookup  = @{}
    $tvdbLookup  = @{}
    $titleLookup = @{}
    foreach ($s in $series) {
        if ($s.imdbId) { $imdbLookup[$s.imdbId]      = $s.title }
        if ($s.tvdbId) { $tvdbLookup["$($s.tvdbId)"] = $s.title }
        $titleLookup[(Normalize $s.title)] = $s.title
        if ($s.originalTitle) { $titleLookup[(Normalize $s.originalTitle)] = $s.title }
    }
    Write-Log ("  Library: {0} series" -f $series.Count) 'White'

    $stats = @{
        NotInArr    = [System.Collections.Generic.List[hashtable]]::new()
        NeedsReview = [System.Collections.Generic.List[hashtable]]::new()
        NameMatched = [System.Collections.Generic.List[hashtable]]::new()
        Matched     = 0
    }

    foreach ($rootPath in $SonarrConfig.Paths) {
        if (-not (Test-Path -LiteralPath $rootPath)) {
            Write-Log ("  [WARN] Path not found: {0}" -f $rootPath) 'Yellow'
            continue
        }
        $folders = Get-ChildItem -LiteralPath $rootPath -Directory -ErrorAction SilentlyContinue
        Write-Log ("  Scanning {0} ({1} folders)" -f $rootPath, $folders.Count) 'White'

        foreach ($folder in $folders) {
            $imdbId = if ($folder.Name -match '\{imdb-(tt\d+)\}') { $Matches[1] } else { $null }
            $tvdbId = if ($folder.Name -match '\{tvdb-(\d+)\}')   { $Matches[1] } else { $null }

            if ($imdbId -or $tvdbId) {
                $hit = ($imdbId -and $imdbLookup.ContainsKey($imdbId)) -or
                       ($tvdbId -and $tvdbLookup.ContainsKey($tvdbId))
                if ($hit) {
                    $stats.Matched++
                } else {
                    $sz    = Get-FolderSize $folder.FullName
                    $idStr = (@($imdbId, $tvdbId) | Where-Object { $_ }) -join ' / '
                    $stats.NotInArr.Add(@{ Path = $folder.FullName; Size = $sz.Display; Bytes = $sz.Bytes; Id = $idStr; App = 'Sonarr' })
                }
            } else {
                $clean   = ($folder.Name -replace '\{[^}]+\}', '' -replace '\s+', ' ').Trim()
                $title   = if ($clean -match '^(.+?)\s*\(\d{4}\)') { $Matches[1].Trim() } else { $clean }
                $nameHit = $titleLookup.ContainsKey((Normalize $title))
                $sz      = Get-FolderSize $folder.FullName
                if ($nameHit) {
                    $stats.Matched++
                    $stats.NameMatched.Add(@{ Path = $folder.FullName; Size = $sz.Display; Bytes = $sz.Bytes; App = 'Sonarr' })
                } else {
                    $stats.NeedsReview.Add(@{ Path = $folder.FullName; Size = $sz.Display; Bytes = $sz.Bytes; App = 'Sonarr' })
                }
            }
        }
    }

    if ($stats.NotInArr.Count) {
        Write-Log ''
        Write-Log '  [ NOT IN SONARR -- ID tag present but not found in Sonarr library ]' 'Red'
        Write-Log '  High confidence orphans. ID tag exists but Sonarr has no matching series.' 'DarkGray'
        foreach ($item in $stats.NotInArr | Sort-Object { $_.Path }) {
            Write-Log ("    {0}  |  {1}  |  ID: {2}" -f $item.Path.PadRight($PathPad), $item.Size.PadLeft(10), $item.Id) 'Red'
        }
    }
    if ($stats.NeedsReview.Count) {
        Write-Log ''
        Write-Log '  [ NEEDS REVIEW -- no ID tag, no name match in Sonarr ]' 'Yellow'
        Write-Log '  No ID tag and name did not match any Sonarr series.' 'DarkGray'
        Write-Log '  May be unmanaged media or folders with slightly different names in Sonarr.' 'DarkGray'
        foreach ($item in $stats.NeedsReview | Sort-Object { $_.Path }) {
            Write-Log ("    {0}  |  {1}" -f $item.Path.PadRight($PathPad), $item.Size.PadLeft(10)) 'Yellow'
        }
    }
    if ($stats.NameMatched.Count) {
        Write-Log ''
        Write-Log '  [ NAME MATCHED (no ID tag) -- counted as matched ]' 'DarkGray'
        Write-Log '  Name matched a Sonarr series but no ID tag to confirm. Run the Sonarr Folder Renamer to add tags.' 'DarkGray'
        foreach ($item in $stats.NameMatched | Sort-Object { $_.Path }) {
            Write-Log ("    {0}  |  {1}" -f $item.Path.PadRight($PathPad), $item.Size.PadLeft(10)) 'DarkGray'
        }
    }

    Write-OrphanAppSummary 'Sonarr' $stats
    return $stats
}

function Invoke-LidarrScan {
    if (-not $LidarrConfig.Enabled) {
        Write-Log '  Lidarr is disabled in config -- skipping.' 'DarkGray'
        return $null
    }

    Write-Log ("  Lidarr: {0}" -f $LidarrConfig.BaseUrl) 'White'
    Write-Tip 'Lidarr Artist Folder Format should be: {Artist Name}'
    Write-Tip 'Lidarr Album Folder Format should be: {Album Title} {(Album Disambiguation)}'
    Write-Tip 'Guide: https://wiki.servarr.com/lidarr/naming-guide'

    $artists = Invoke-ArrApi $LidarrConfig.BaseUrl $LidarrConfig.ApiKey 'artist' 'v1'
    if (-not $artists) {
        Write-Log '  Could not reach Lidarr API. Check BaseUrl and ApiKey in FolderBoy.config.ps1.' 'Red'
        return $null
    }

    $artistLookup = @{}
    foreach ($a in $artists) { $artistLookup[(Normalize $a.artistName)] = $a.artistName }
    Write-Log ("  Library: {0} artists" -f $artists.Count) 'White'

    $stats = @{
        NotInArr    = [System.Collections.Generic.List[hashtable]]::new()
        NeedsReview = [System.Collections.Generic.List[hashtable]]::new()
        NameMatched = [System.Collections.Generic.List[hashtable]]::new()
        Matched     = 0
    }

    foreach ($rootPath in $LidarrConfig.Paths) {
        if (-not (Test-Path -LiteralPath $rootPath)) {
            Write-Log ("  [WARN] Path not found: {0}" -f $rootPath) 'Yellow'
            continue
        }
        $folders = Get-ChildItem -LiteralPath $rootPath -Directory -ErrorAction SilentlyContinue
        Write-Log ("  Scanning {0} ({1} artist folders)" -f $rootPath, $folders.Count) 'White'

        foreach ($folder in $folders) {
            $normName = Normalize $folder.Name
            if ($artistLookup.ContainsKey($normName)) {
                $stats.Matched++
            } else {
                $stripped = $normName -replace '[^a-z0-9]', ''
                $fuzzyHit = $artistLookup.Keys |
                    Where-Object { ($_ -replace '[^a-z0-9]', '') -eq $stripped } |
                    Select-Object -First 1
                $sz = Get-FolderSize $folder.FullName
                if ($fuzzyHit) {
                    $stats.NeedsReview.Add(@{
                        Path       = $folder.FullName
                        Size       = $sz.Display
                        Bytes      = $sz.Bytes
                        FuzzyMatch = $artistLookup[$fuzzyHit]
                        App        = 'Lidarr'
                    })
                } else {
                    $stats.NotInArr.Add(@{ Path = $folder.FullName; Size = $sz.Display; Bytes = $sz.Bytes; App = 'Lidarr' })
                }
            }
        }
    }

    if ($stats.NotInArr.Count) {
        Write-Log ''
        Write-Log '  [ NOT IN LIDARR -- artist folder not managed by Lidarr ]' 'Red'
        foreach ($item in $stats.NotInArr | Sort-Object { $_.Path }) {
            Write-Log ("    {0}  |  {1}" -f $item.Path.PadRight($PathPad), $item.Size.PadLeft(10)) 'Red'
        }
    }
    if ($stats.NeedsReview.Count) {
        Write-Log ''
        Write-Log '  [ NEEDS REVIEW -- fuzzy name match only, verify before deleting ]' 'Yellow'
        Write-Log '  Closely resembles a Lidarr artist name but did not match exactly.' 'DarkGray'
        Write-Log '  Parenthetical suffixes in folder names are a common cause.' 'DarkGray'
        foreach ($item in $stats.NeedsReview | Sort-Object { $_.Path }) {
            Write-Log ("    {0}  |  {1}  |  Possible match: {2}" -f $item.Path.PadRight($PathPad), $item.Size.PadLeft(10), $item.FuzzyMatch) 'Yellow'
        }
    }

    Write-OrphanAppSummary 'Lidarr' $stats
    return $stats
}

function Invoke-OrphanInteractiveDelete ($RadarrStats, $SonarrStats, $LidarrStats) {
    $notInArr    = [System.Collections.Generic.List[hashtable]]::new()
    $needsReview = [System.Collections.Generic.List[hashtable]]::new()
    $nameMatched = [System.Collections.Generic.List[hashtable]]::new()

    foreach ($stats in @($RadarrStats, $SonarrStats, $LidarrStats)) {
        if (-not $stats) { continue }
        foreach ($item in $stats.NotInArr)    { $notInArr.Add($item) }
        foreach ($item in $stats.NeedsReview) { $needsReview.Add($item) }
        if ($stats.NameMatched) { foreach ($item in $stats.NameMatched) { $nameMatched.Add($item) } }
    }

    $totalAll = $notInArr.Count + $needsReview.Count + $nameMatched.Count
    if ($totalAll -eq 0) {
        Write-Log ''
        Write-Log '  No orphaned items found. Nothing to delete.' 'Green'
        return
    }

    Write-Log ''
    Write-Log '  ============================================================' 'Cyan'
    Write-Log '   SELECT ITEMS TO REVIEW FOR DELETION' 'Cyan'
    Write-Log '  ============================================================' 'Cyan'
    Write-Log ''
    Write-Log '  Confidence levels:' 'DarkGray'
    Write-Log '    NOT IN ARR   -- High.   ID tag present but not found in *arr library.' 'DarkGray'
    Write-Log '    NEEDS REVIEW -- Medium. No ID tag and no name match found in *arr.' 'DarkGray'
    Write-Log '    NAME MATCHED -- Low.    Name matched but no ID tag to confirm.' 'DarkGray'
    Write-Log ''
    Write-Log ("  (1) NOT IN ARR only             ({0,4} items -- high confidence)" -f $notInArr.Count) 'White'
    Write-Log ("  (2) NOT IN ARR + NEEDS REVIEW   ({0,4} items)" -f ($notInArr.Count + $needsReview.Count)) 'White'
    Write-Log ("  (3) ALL flagged items            ({0,4} items -- includes low-confidence)" -f $totalAll) 'White'
    Write-Log ("  (4) Exit without deleting") 'White'
    Write-Log ''

    do { $catChoice = Read-Host '  Choice' } until ($catChoice -in '1','2','3','4')
    if ($catChoice -eq '4') { Write-Log '  Exited. No changes made.' 'Yellow'; return }

    $candidates = [System.Collections.Generic.List[hashtable]]::new()
    foreach ($item in $notInArr) { $candidates.Add($item) }
    if ($catChoice -in '2','3') { foreach ($item in $needsReview) { $candidates.Add($item) } }
    if ($catChoice -eq '3')     { foreach ($item in $nameMatched) { $candidates.Add($item) } }
    $candidates = $candidates | Sort-Object { $_.Path }

    Write-Log ''
    Write-Log '  ============================================================' 'Cyan'
    Write-Log ("   REVIEWING {0} ITEMS" -f $candidates.Count) 'Cyan'
    Write-Log '   (D)elete  (S)kip  (Q)uit review' 'Cyan'
    Write-Log '  ============================================================' 'Cyan'
    Write-Log ''
    Write-Log '  Items marked D are queued -- nothing is deleted until you confirm at the end.' 'DarkGray'

    $deleteQueue = [System.Collections.Generic.List[hashtable]]::new()
    $skipped     = 0
    $quitEarly   = $false

    foreach ($item in $candidates) {
        Write-Log ''
        Write-Log ("  Path : {0}" -f $item.Path) 'White'
        Write-Log ("  Size : {0}  |  App: {1}" -f $item.Size, $item.App) 'White'
        if ($item.Id)         { Write-Log ("  ID   : {0}" -f $item.Id) 'DarkGray' }
        if ($item.FuzzyMatch) { Write-Log ("  Note : Possible {0} match -- {1}" -f $item.App, $item.FuzzyMatch) 'Yellow' }

        do { $choice = (Read-Host '  (D)elete / (S)kip / (Q)uit').ToUpper().Trim() } until ($choice -in 'D','S','Q')

        switch ($choice) {
            'D' { $deleteQueue.Add($item); Write-Log '  --> Queued for deletion' 'Red' }
            'S' { $skipped++; Write-Log '  --> Skipped' 'DarkGray' }
            'Q' { $quitEarly = $true; Write-Log '  --> Review stopped by user' 'Yellow' }
        }
        if ($quitEarly) { break }
    }

    if ($deleteQueue.Count -eq 0) {
        Write-Log ''
        Write-Log '  No items queued for deletion.' 'Yellow'
        return
    }

    $totalBytes = ($deleteQueue | Measure-Object -Property Bytes -Sum).Sum
    $totalGB    = [math]::Round($totalBytes / 1GB, 2)
    $totalMB    = [math]::Round($totalBytes / 1MB, 1)

    Write-Log ''
    Write-Log '  ============================================================' 'Cyan'
    Write-Log '   DELETION QUEUE' 'Cyan'
    Write-Log '  ============================================================' 'Cyan'
    Write-Log ("  Items queued : {0}" -f $deleteQueue.Count) 'Red'
    Write-Log ("  Items skipped: {0}" -f $skipped) 'DarkGray'
    Write-Log ("  Total size   : {0} GB  ({1} MB)" -f $totalGB, $totalMB) 'Red'
    Write-Log ''
    foreach ($item in $deleteQueue) {
        Write-Log ("    {0}  |  {1}" -f $item.Path.PadRight($PathPad), $item.Size.PadLeft(10)) 'Red'
    }

    if (-not (Confirm-LiveAction 'The folders listed above will be permanently deleted.')) { return }

    Write-Log ''
    Write-SectionHeader 'DELETING'

    $deleted = 0; $failed = 0; $deletedBytes = [long]0

    foreach ($item in $deleteQueue) {
        if (-not (Test-Path -LiteralPath $item.Path)) {
            Write-Log ("  [SKIP]    {0} -- no longer exists on disk" -f $item.Path) 'Yellow'
            continue
        }
        try {
            Remove-Item -LiteralPath $item.Path -Recurse -Force -ErrorAction Stop
            Write-Log ("  [DELETED] {0}  ({1})" -f $item.Path.PadRight($PathPad), $item.Size) 'Green'
            $deleted++
            $deletedBytes += $item.Bytes
        } catch {
            Write-Log ("  [FAILED]  {0}" -f $item.Path) 'Red'
            Write-Log ("            {0}" -f $_) 'Red'
            $failed++
        }
    }

    $deletedGB = [math]::Round($deletedBytes / 1GB, 2)
    $deletedMB = [math]::Round($deletedBytes / 1MB, 1)

    Write-Log ''
    Write-Log ("  Deleted : {0}  folders  |  {1} GB  ({2} MB) reclaimed" -f $deleted, $deletedGB, $deletedMB) 'Green'
    Write-Log ("  Failed  : {0}  folders" -f $failed) $(if ($failed) { 'Red' } else { 'Green' })
}

function Invoke-OrphanScanner {
    param([bool]$WithDelete = $false)

    Start-Log 'FolderBoy_Scanner'

    Write-Log ''
    Write-Log '  ============================================================' 'Cyan'
    $scanModeLabel = if ($WithDelete) { 'Scan + Delete' } else { 'Scan Only' }
    Write-Log ("   Orphan Scanner -- {0}" -f $scanModeLabel) 'Cyan'
    Write-Log ('   {0}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')) 'Cyan'
    Write-Log '  ============================================================' 'Cyan'

    if (-not $WithDelete) {
        Write-Log ''
        Write-Log '  SCAN ONLY MODE: No files will be deleted.' 'Cyan'
        Write-Log '  This run reports orphaned folders only.' 'Cyan'
        Write-Log '  Re-run and choose Scan + Delete to act on the results.' 'Cyan'
    }

    Write-Log ''
    Write-Log '  Scanning libraries...' 'White'

    Write-SectionHeader 'RADARR'
    $radarrStats = Invoke-RadarrScan

    Write-SectionHeader 'SONARR'
    $sonarrStats = Invoke-SonarrScan

    Write-SectionHeader 'LIDARR'
    $lidarrStats = Invoke-LidarrScan

    Write-Log ''
    Write-Log '  ============================================================' 'Cyan'
    Write-Log '   OVERALL SUMMARY' 'Cyan'
    Write-Log '  ============================================================' 'Cyan'

    $grandNotInArr = 0; $grandNeedsReview = 0; $grandMatched = 0

    foreach ($pair in @(
        @{ Name = 'Radarr'; Stats = $radarrStats; Cfg = $RadarrConfig },
        @{ Name = 'Sonarr'; Stats = $sonarrStats; Cfg = $SonarrConfig },
        @{ Name = 'Lidarr'; Stats = $lidarrStats; Cfg = $LidarrConfig }
    )) {
        if (-not $pair.Cfg.Enabled) {
            Write-Log ("  {0,-10}  Disabled" -f $pair.Name) 'DarkGray'
        } elseif ($pair.Stats) {
            $grandNotInArr    += $pair.Stats.NotInArr.Count
            $grandNeedsReview += $pair.Stats.NeedsReview.Count
            $grandMatched     += $pair.Stats.Matched
            Write-Log ("  {0,-10}  Not in arr: {1,4}   Needs review: {2,4}   Matched: {3,4}" -f `
                $pair.Name, $pair.Stats.NotInArr.Count, $pair.Stats.NeedsReview.Count, $pair.Stats.Matched) 'White'
        } else {
            Write-Log ("  {0,-10}  SKIPPED (API unreachable)" -f $pair.Name) 'Red'
        }
    }

    Write-Log ''
    Write-Log ("  Total NOT IN ARR   : {0}" -f $grandNotInArr)    $(if ($grandNotInArr)    { 'Red'    } else { 'Green' })
    Write-Log ("  Total NEEDS REVIEW : {0}" -f $grandNeedsReview) $(if ($grandNeedsReview) { 'Yellow' } else { 'Green' })
    Write-Log ("  Total MATCHED OK   : {0}" -f $grandMatched)     'Green'
    Write-Log ''
    Write-Log ("  Log saved to: {0}" -f $Script:LogFile) 'Cyan'

    if ($WithDelete) {
        Invoke-OrphanInteractiveDelete $radarrStats $sonarrStats $lidarrStats
    }
}

