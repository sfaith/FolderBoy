# ================================================================
#  TOOL 4: LIDARR FOLDER RENAMER
# ================================================================
function Get-LidarrCleanArtistName ([string]$Name) {
    $clean = $Name -replace ':', ' -'
    $clean = $clean -replace '[\\/<>"\|\?\*]', ''
    $clean = $clean -replace '\s+', ' '
    $clean = $clean.Trim()
    $clean = $clean.TrimEnd('.')
    return $clean
}

